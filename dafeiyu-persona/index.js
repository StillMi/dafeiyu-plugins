const DEFAULT_NAME = 'dafeiyu:persona-guard'

export const inject = ['systemPrompt']

export function apply(ctx, rawConfig) {
  const cfg = rawConfig ?? {}
  const log = ctx.logger ?? console

  const text = typeof cfg.text === 'string' && cfg.text.trim().length > 0 ? cfg.text : DEFAULT_PERSONA
  const name = typeof cfg.name === 'string' && cfg.name.trim().length > 0 ? cfg.name.trim() : DEFAULT_NAME

  // 排在 deployment persona 之后、plan policy 之前。
  // DEPLOYMENT_PERSONA_PREFIX = 0，PLAN_POLICY = 500，取 1 就贴在人格后面。
  const order = Number.isFinite(cfg.order) ? cfg.order : 1

  ctx.effect(
    () =>
      ctx.systemPrompt.section({
        name,
        order,
        text,
      }),
    'dafeiyu-persona.section()',
  )

  log.info?.(`[dafeiyu-persona] 已挂上人格提醒 ${text.length} 字（section=${name}, order=${order}）`)
}
